const COUNTRIES = Object.entries(COUNTRY_GROUPS).flatMap(([level, rows]) => rows.split('\n').map(row => {
  const [id, name] = row.split('|'); return {id, name, level};
}));
function makeQuestions(level, count = 30, rng = Math.random) {
  const pool = COUNTRIES.filter(c => level === 'random' || c.level === level);
  if (pool.length < count) throw new Error('出題できる国が不足しています。');
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1)); [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}
if (typeof module !== 'undefined') module.exports = {COUNTRIES, makeQuestions};
